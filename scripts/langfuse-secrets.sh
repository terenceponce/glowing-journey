#!/usr/bin/env bash
# Generate Langfuse credentials into secrets/langfuse.env (git-ignored) on first run,
# then (re)create the Kubernetes Secrets from it:
#   langfuse/langfuse       app secrets + datastore passwords for the Helm chart
#   langfuse/langfuse-init  LANGFUSE_INIT_* headless-init vars for langfuse-web
#   app/langfuse-api        project API keys for the chatbot
#
# Re-running keeps the existing values, so the salt, encryption key and API keys stay stable.
set -euo pipefail

KUBECTL=${KUBECTL:-kubectl --context kind-obs-lab}
ENV_FILE=${ENV_FILE:-secrets/langfuse.env}

hex() { openssl rand -hex "$1"; }
uuid() { uuidgen | tr '[:upper:]' '[:lower:]'; }

if [[ ! -f "$ENV_FILE" ]]; then
  echo "Generating $ENV_FILE"
  mkdir -p "$(dirname "$ENV_FILE")"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by scripts/langfuse-secrets.sh. Do not commit.
SALT=$(openssl rand -base64 32)
ENCRYPTION_KEY=$(hex 32)
NEXTAUTH_SECRET=$(openssl rand -base64 32)
POSTGRES_PASSWORD=$(hex 24)
CLICKHOUSE_PASSWORD=$(hex 24)
REDIS_PASSWORD=$(hex 24)
S3_USER=langfuse
S3_PASSWORD=$(hex 24)

LANGFUSE_INIT_ORG_ID=obs-lab
LANGFUSE_INIT_ORG_NAME=obs-lab
LANGFUSE_INIT_PROJECT_ID=rag-chatbot
LANGFUSE_INIT_PROJECT_NAME=rag-chatbot
LANGFUSE_INIT_PROJECT_PUBLIC_KEY=pk-lf-$(uuid)
LANGFUSE_INIT_PROJECT_SECRET_KEY=sk-lf-$(uuid)
LANGFUSE_INIT_USER_EMAIL=admin@obs-lab.local
LANGFUSE_INIT_USER_NAME=admin
LANGFUSE_INIT_USER_PASSWORD=$(hex 12)
EOF
else
  echo "Using existing $ENV_FILE"
fi

set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Chart secret (key layout from langfuse-k8s examples/minimal-installation/secret.yaml).
# One file per key, so the SeaweedFS JSON config can sit next to the plain values.
chart="$tmp/langfuse"
mkdir "$chart"
put() { printf '%s' "$2" > "$chart/$1"; }
put salt "$SALT"
put encryption-key "$ENCRYPTION_KEY"
put nextauth-secret "$NEXTAUTH_SECRET"
put postgresql-password "$POSTGRES_PASSWORD"
put POSTGRES_USER postgres
put POSTGRES_PASSWORD "$POSTGRES_PASSWORD"
put POSTGRES_DB langfuse
put USERDB_USER langfuse
put USERDB_PASSWORD "$POSTGRES_PASSWORD"
put clickhouse-password "$CLICKHOUSE_PASSWORD"
put redis-password "$REDIS_PASSWORD"
put default "$REDIS_PASSWORD"
put s3-user "$S3_USER"
put s3-password "$S3_PASSWORD"
put seaweedfs_s3_config "$(printf '{"identities":[{"name":"%s","credentials":[{"accessKey":"%s","secretKey":"%s"}],"actions":["Admin","Read","Write","List","Tagging"]}]}' \
  "$S3_USER" "$S3_USER" "$S3_PASSWORD")"

grep '^LANGFUSE_INIT_' "$ENV_FILE" > "$tmp/init.env"

cat > "$tmp/api.env" <<EOF
LANGFUSE_PUBLIC_KEY=$LANGFUSE_INIT_PROJECT_PUBLIC_KEY
LANGFUSE_SECRET_KEY=$LANGFUSE_INIT_PROJECT_SECRET_KEY
EOF

apply_secret() {
  local ns=$1 name=$2; shift 2
  $KUBECTL -n "$ns" create secret generic "$name" "$@" --dry-run=client -o yaml | $KUBECTL apply -f -
}

apply_secret langfuse langfuse --from-file="$chart"
apply_secret langfuse langfuse-init --from-env-file="$tmp/init.env"
apply_secret app langfuse-api --from-env-file="$tmp/api.env"
